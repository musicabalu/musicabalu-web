async function main() {
  const existing = await prisma.adminNote.findFirst({
    where: { title }
  });

  if (existing) {
    const updated = await prisma.adminNote.update({
      where: { id: existing.id },
      data: { content, category }
    });
    console.log("Nota actualizada con éxito en DB:", updated.id);
  } else {
    const created = await prisma.adminNote.create({
      data: { title, category, content }
    });
    console.log("Nueva nota creada con éxito en DB:", created.id);
  }
}

main()
  .catch(err => {
    console.error("Error al guardar la nota:", err);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
